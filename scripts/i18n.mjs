export function validateParts(parts, locale) {
  const numbers = parts.map(({ number }) => number);
  const expected = Array.from({ length: EXPECTED_PARTS }, (_, index) => index + 1);
  if (numbers.length !== EXPECTED_PARTS || numbers.some((number, index) => number !== expected[index])) {
    throw new Error(`${locale}: expected exactly 38 ordered parts (1–38); found ${numbers.join(", ") || "none"}.`);
  }
}
